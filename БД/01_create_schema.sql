-- ===========================================
-- СОЗДАНИЕ СХЕМЫ TAIGA
-- ===========================================
-- Этот скрипт создаёт схему taiga в PostgreSQL
-- Выполнить перед созданием таблиц
-- ===========================================

-- Создание схемы taiga
CREATE SCHEMA IF NOT EXISTS taiga;

-- Установка прав доступа
GRANT ALL PRIVILEGES ON SCHEMA taiga TO marabot;

-- Установка схемы по умолчанию для текущей сессии
SET search_path TO taiga, public;

-- Сообщение об успешном создании
DO $$
BEGIN
    RAISE NOTICE '✅ Схема taiga успешно создана!';
END $$;



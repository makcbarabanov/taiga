SET search_path TO taiga, public;

-- 1. Увеличиваем размер поля status для новых статусов
ALTER TABLE taiga.employees 
    ALTER COLUMN status TYPE VARCHAR(30);

-- 2. Обновляем комментарий к колонке
COMMENT ON COLUMN taiga.employees.status IS 'Статус сотрудника: Работает, Уволен, Не указан, Кандидат, Запас, Консультант, Подрядчик, Временный (автоматически обновляется по датам, если статус не установлен вручную)';

-- 3. Обновляем функцию для автоматического обновления статуса
-- Теперь она не перезаписывает статусы, установленные вручную
CREATE OR REPLACE FUNCTION taiga.update_employee_status()
RETURNS TRIGGER AS $$
BEGIN
    -- Список статусов, которые устанавливаются вручную и не должны перезаписываться
    -- Если статус уже установлен вручную, не меняем его автоматически
    IF NEW.status IN ('Кандидат', 'Запас', 'Консультант', 'Подрядчик', 'Временный') THEN
        -- Если статус установлен вручную, сохраняем его
        RETURN NEW;
    END IF;
    
    -- Автоматическое определение статуса только для стандартных случаев
    -- Если есть дата увольнения - статус "Уволен"
    IF NEW.dismissal_date IS NOT NULL THEN
        NEW.status = 'Уволен';
    -- Если есть дата трудоустройства и нет даты увольнения - статус "Работает"
    ELSIF NEW.hire_date IS NOT NULL AND NEW.dismissal_date IS NULL THEN
        NEW.status = 'Работает';
    -- Иначе - статус остаётся "Не указан" или сохраняется текущий
    ELSE
        NEW.status = COALESCE(OLD.status, 'Не указан');
    END IF;
    
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

COMMENT ON FUNCTION taiga.update_employee_status() IS 'Автоматически обновляет статус сотрудника на основе дат трудоустройства и увольнения. Не перезаписывает статусы, установленные вручную (Кандидат, Запас, Консультант, Подрядчик, Временный)';

